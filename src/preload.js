const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('limpa', {
  openPhotos: () => ipcRenderer.invoke('photos:open'),
  getPrivacyBrowsers: () => ipcRenderer.invoke('privacy:browsers'),
  openPrivacyBrowser: id => ipcRenderer.invoke('privacy:open',id),
  getCompletionSound: () => ipcRenderer.invoke('feedback:get'),
  setCompletionSound: enabled => ipcRenderer.invoke('feedback:set', enabled),
  taskComplete: () => ipcRenderer.invoke('feedback:complete'),
  getPerformance: () => ipcRenderer.invoke('performance:list'),
  getPerformanceMetrics: () => ipcRenderer.invoke('performance:metrics'),
  prepareProcess: (pid, options) => ipcRenderer.invoke('performance:prepare-process', pid, options),
  terminateProcess: confirmation => ipcRenderer.invoke('performance:terminate', confirmation),
  prepareService: id => ipcRenderer.invoke('performance:prepare-service', id),
  unloadService: confirmation => ipcRenderer.invoke('performance:unload-service', confirmation),
  getApplications: () => ipcRenderer.invoke('applications:list'),
  prepareUninstall: id => ipcRenderer.invoke('applications:prepare',id),
  uninstallApp: confirmation => ipcRenderer.invoke('applications:uninstall',confirmation),
  revealApplication: id => ipcRenderer.invoke('applications:reveal',id),
  onEscape: fn => ipcRenderer.on('window:escape',()=>fn()),
  onPhotosChanged: (fn) => ipcRenderer.on('photos:changed', () => fn()),
  checkUpdates: () => ipcRenderer.invoke('updates:check'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  onUpdateProgress: (fn) => ipcRenderer.on('updates:progress', (_e, p) => fn(p)),
  onUpdates: (fn) => ipcRenderer.on('updates:changed', (_e, state) => fn(state)),
  init: () => ipcRenderer.invoke('app:init'),
  getAppearance: () => ipcRenderer.invoke('appearance:get'),
  setAppearance: (mode) => ipcRenderer.invoke('appearance:set', mode),
  onAppearance: (fn) => {
    const listener = (_event, state) => fn(state);
    ipcRenderer.on('appearance:changed', listener);
    return () => ipcRenderer.removeListener('appearance:changed', listener);
  },
  diskInfo: () => ipcRenderer.invoke('disk:info'),
  analyze: (id) => ipcRenderer.invoke('category:analyze', id),
  clean: (ids, confirmation) => ipcRenderer.invoke('categories:clean', ids, confirmation),
  setCategory: (id, enabled) => ipcRenderer.invoke('config:set-category', id, enabled),
  reveal: (p) => ipcRenderer.invoke('finder:reveal', p),
  getVolumes: () => ipcRenderer.invoke('volumes:list'),
  lastVolumeFolders: id => ipcRenderer.invoke('volumes:folders-last', id),
  analyzeVolumeFolders: id => ipcRenderer.invoke('volumes:folders-analyze', id),
  cancelVolumeFolders: id => ipcRenderer.invoke('volumes:folders-cancel', id),
  ejectVolume: (id) => ipcRenderer.invoke('volumes:eject', id),
  onVolumes: (fn) => ipcRenderer.on('volumes:changed', (_e, list) => fn(list)),
  setTrashDays: (days) => ipcRenderer.invoke('config:set-trash-days', days),
  openCategory: (id) => ipcRenderer.invoke('category:open', id),
  getNetwork: () => ipcRenderer.invoke('network:info'),
  getBluetooth: () => ipcRenderer.invoke('bluetooth:list'),
  lastFolders: () => ipcRenderer.invoke('folders:last'),
  analyzeFolders: () => ipcRenderer.invoke('folders:analyze'),
  cancelFolders: () => ipcRenderer.send('folders:cancel'),
  revealFolder: (id) => ipcRenderer.invoke('folders:reveal', id),
  runSpeedTest: () => ipcRenderer.invoke('network:speed'),
  openSite: () => ipcRenderer.send('app:open-site'),
  openAccount: () => ipcRenderer.invoke('app:open-account'),
  getSchedule: () => ipcRenderer.invoke('schedule:get'),
  setSchedule: (patch) => ipcRenderer.invoke('schedule:set', patch),
  openPrivacy: (permission) => ipcRenderer.send('app:open-privacy', permission),
  hide: () => ipcRenderer.send('window:hide'),
  quit: () => ipcRenderer.send('app:quit'),
  onShown: (fn) => ipcRenderer.on('window:shown', () => fn()),
  onHidden: (fn) => ipcRenderer.on('window:hidden', () => fn()),
});
